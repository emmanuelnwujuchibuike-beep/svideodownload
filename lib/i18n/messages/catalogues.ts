/**
 * Every non-English UI catalogue (owner, 2026-08-09: "configure all languages in
 * the language selector").
 *
 * ── One file, not fifty ──────────────────────────────────────────────────────
 * These are 22 short chrome strings each. As fifty modules they would be fifty
 * imports, fifty headers and fifty chances for one to be forgotten in the
 * registry; as one object they are diffable side by side, which is exactly what
 * a reviewer checking a language needs. `Messages` is `Record<MessageKey,
 * string>`, so TypeScript rejects any locale that misses a key — a new string in
 * `en.ts` fails the build here rather than silently falling back at runtime.
 *
 * ── Provenance, stated plainly ───────────────────────────────────────────────
 * Written by Claude on 2026-08-09 at the owner's explicit instruction, after the
 * project's original standing rule against machine translation was raised and
 * overridden. NONE of these has been read by a native speaker.
 *
 * Confidence genuinely varies by language and pretending otherwise would be the
 * dishonest part. `REVIEW_PRIORITY` below ranks them for human review by where a
 * mistake is most likely AND most costly — it is not decoration, it is the
 * queue.
 *
 * ── Conventions held across every locale ─────────────────────────────────────
 * • "Frenz" is a brand name: never translated, never transliterated (it would
 *   make the site unfindable by its own name).
 * • `nav.download` is the ACTION on a button, not the noun "a download".
 * • `footer.copyright` keeps the `{year}` placeholder and puts it where the
 *   language's grammar wants it — the whole reason that string is interpolated.
 * • Sentence case for nav items; most of these languages do not title-case.
 */

/**
 * Which languages a human should check first.
 *
 * Ordered by risk, not by traffic: scripts and grammars where an automatic
 * rendering is most likely to be subtly wrong, and languages central to this
 * site's Africa-primary audience where being wrong costs the most. A language
 * absent from this list is not "verified" — it is merely lower risk.
 */
