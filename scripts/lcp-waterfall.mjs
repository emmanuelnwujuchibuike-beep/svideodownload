/**
 * What is the LCP element WAITING ON? — the waterfall, not the number.
 *
 * `lcp-profile.mjs` said the landing's LCP element is an `<IMG>` whose
 * `renderTime` lands ~35ms after its own `loadTime`. That makes LCP a RESOURCE
 * arrival, not a paint or a hydration task — so the only useful next artefact
 * is when that request was discovered, when it started, and what was in front
 * of it in the queue.
 *
 *   node scripts/lcp-waterfall.mjs
 *   LCP_URL=https://frenzsave.com/ LCP_PROFILE=slow4g node scripts/lcp-waterfall.mjs
 */
import { chromium, devices } from "playwright";

const TARGET = process.env.LCP_URL ?? "https://frenzsave.com/";
const PROFILE = process.env.LCP_PROFILE ?? "slow4g";
const RUNS = Number(process.env.LCP_RUNS ?? 2);

const NET = {
  slow4g: { latency: 150, down: (1.6 * 1024 * 1024) / 8, up: (750 * 1024) / 8, cpu: 4 },
  fast4g: { latency: 40, down: (10 * 1024 * 1024) / 8, up: (10 * 1024 * 1024) / 8, cpu: 2 },
  none: null,
};

const COLLECT = [
  "window.__lcp = [];",
  "new PerformanceObserver((l) => {",
  "  for (const e of l.getEntries()) {",
  "    const el = e.element;",
  "    window.__lcp.push({ t: Math.round(e.startTime), el: el ? el.tagName : null,",
  "      src: (el && (el.currentSrc || el.src)) || '',",
  "      loadTime: Math.round(e.loadTime || 0), renderTime: Math.round(e.renderTime || 0),",
  "      fetchpriority: el ? el.getAttribute('fetchpriority') : null,",
  "      loading: el ? el.getAttribute('loading') : null,",
  "      decoding: el ? el.getAttribute('decoding') : null,",
  "      inInitialHtml: null });",
  "  }",
  "}).observe({ type: 'largest-contentful-paint', buffered: true });",
].join("\n");

const READ = [
  "(() => {",
  "  const nav = performance.getEntriesByType('navigation')[0];",
  "  const fcp = performance.getEntriesByName('first-contentful-paint')[0];",
  "  const res = performance.getEntriesByType('resource').map((r) => ({",
  "    name: r.name, start: Math.round(r.startTime), end: Math.round(r.responseEnd),",
  "    dur: Math.round(r.duration), size: r.transferSize, enc: r.encodedBodySize,",
  "    dec: r.decodedBodySize, type: r.initiatorType, block: r.renderBlockingStatus || '',",
  "  }));",
  "  return { lcp: window.__lcp, res, fcp: fcp ? Math.round(fcp.startTime) : null,",
  "    ttfb: nav ? Math.round(nav.responseStart) : null, load: nav ? Math.round(nav.loadEventStart) : null };",
  "})()",
].join("\n");

const short = (u) => u.replace(/^https?:\/\/[^/]+/, "").slice(0, 96);
const kb = (n) => (n ? (n / 1024).toFixed(1) + "kB" : "-");

const browser = await chromium.launch();
for (let run = 0; run < RUNS; run++) {
  const ctx = await browser.newContext({ ...devices["Pixel 7"] });
  const page = await ctx.newPage();
  const cdp = await ctx.newCDPSession(page);
  const net = NET[PROFILE];
  if (net) {
    await cdp.send("Network.emulateNetworkConditions", {
      offline: false, latency: net.latency, downloadThroughput: net.down, uploadThroughput: net.up,
    });
    await cdp.send("Emulation.setCPUThrottlingRate", { rate: net.cpu });
  }
  await page.addInitScript(COLLECT);

  /* The raw HTML, fetched separately, is the only way to answer "was the LCP
     image discoverable by the preload scanner or only after hydration?". */
  let html = "";
  page.on("response", async (r) => {
    if (r.url() === TARGET || r.url() === TARGET.replace(/\/$/, "")) {
      html = await r.text().catch(() => "");
    }
  });

  await page.goto(TARGET, { waitUntil: "load", timeout: 90_000 }).catch(() => {});
  await page.waitForTimeout(2000);
  const out = await page.evaluate(READ);
  await ctx.close();

  const lcp = out.lcp[out.lcp.length - 1] ?? {};
  console.log("\n======== run" + (run + 1) + " [" + PROFILE + "]  TTFB " + out.ttfb + "  FCP " + out.fcp + "  LCP " + lcp.t + "  load " + out.load);
  console.log("LCP <" + lcp.el + "> loadTime=" + lcp.loadTime + " renderTime=" + lcp.renderTime +
    " fetchpriority=" + lcp.fetchpriority + " loading=" + lcp.loading + " decoding=" + lcp.decoding);
  console.log("LCP src: " + short(lcp.src || ""));

  if (lcp.src) {
    const path = decodeURIComponent(short(lcp.src));
    /* The `url=` parameter is what the page's own markup contains; the
       /_next/image wrapper around it is generated by next/image at render. */
    const inner = (lcp.src.match(/url=([^&]+)/) || [])[1];
    const raw = inner ? decodeURIComponent(inner) : null;
    console.log("LCP underlying url: " + (raw ? raw.slice(0, 110) : "(not a /_next/image request)"));
    console.log("  in initial HTML as <img src>?      " + html.includes(lcp.src.split("?")[0] + "?" + (lcp.src.split("?")[1] || "").slice(0, 40)));
    console.log("  underlying url present in HTML?    " + (raw ? html.includes(raw.slice(0, 60)) : "n/a"));
    console.log("  <link rel=preload as=image> in HTML? " + /rel="?preload"?[^>]*as="?image/.test(html));
    const entry = out.res.find((r) => r.name === lcp.src);
    if (entry) {
      console.log("  request: start " + entry.start + "  end " + entry.end + "  dur " + entry.dur +
        "  transfer " + kb(entry.size) + "  encoded " + kb(entry.enc) + "  initiator " + entry.type);
    }
  }
  console.log("HTML bytes: " + kb(html.length));

  console.log("\n-- everything that finished before LCP, by start --");
  for (const r of out.res.filter((r) => r.start < lcp.t).sort((a, b) => a.start - b.start)) {
    console.log(
      String(r.start).padStart(6) + " -> " + String(r.end).padStart(6) +
      " (" + String(r.dur).padStart(5) + "ms) " + kb(r.size).padStart(9) +
      " " + (r.block === "blocking" ? "BLOCKING " : "         ") + r.type.padEnd(10) + " " + short(r.name),
    );
  }
}
await browser.close();
