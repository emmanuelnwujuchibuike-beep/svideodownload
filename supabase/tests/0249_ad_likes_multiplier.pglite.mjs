// PGlite harness for 0249 (ad likes follow the x10 sample mode). node t0249.mjs <0249.sql> [--mutant]
import { readFileSync } from "node:fs";
import { PGlite } from "@electric-sql/pglite";
const file = process.argv[2];
const MUTANT = process.argv.includes("--mutant");
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role;
create table ad_campaigns (id uuid primary key, status text, stats_multiplier integer not null default 1);
create table ad_campaign_daily_stats (campaign_id uuid, day date, impressions integer);
create table ad_campaign_engagement (campaign_id uuid primary key, likes integer not null default 0, shares integer not null default 0, updated_at timestamptz);
create table ad_campaign_reactions (campaign_id uuid, kind text, actor_key text, user_id uuid);
insert into ad_campaigns values ('00000000-0000-4000-8000-000000000001','active',1), ('00000000-0000-4000-8000-000000000002','active',10);
insert into ad_campaign_daily_stats values ('00000000-0000-4000-8000-000000000001', current_date, 37), ('00000000-0000-4000-8000-000000000002', current_date, 37);
insert into ad_campaign_engagement values ('00000000-0000-4000-8000-000000000001', 3, 2, now()), ('00000000-0000-4000-8000-000000000002', 3, 2, now());
insert into ad_campaign_reactions values ('00000000-0000-4000-8000-000000000002','like','v:visit12345',null);`);
let sql = readFileSync(file, "utf8");
if (MUTANT) sql = sql.replace("'likes', coalesce(e.likes, 0)::bigint * greatest(1, coalesce((to_jsonb(c) ->> 'stats_multiplier')::integer, 1)),", "'likes', coalesce(e.likes, 0),");
const run = async () => { for (const s of sql.split(/;\s*\n(?=(?:create|do)\b)/)) await db.exec(s); };
await run(); await run();
let failures = 0;
const ok = (c, m) => { if (!c) { failures++; console.log("FAIL:", m); } else console.log("ok:", m); };
const eng = async (id, actor = null) => (await db.query(`select ad_engagement($1, $2) e`, [id, actor])).rows[0].e;
const off = await eng("00000000-0000-4000-8000-000000000001");
ok(off.likes === 3 && off.views === 37 && off.shares === 2, "switch off: real likes, views and shares");
const on = await eng("00000000-0000-4000-8000-000000000002", "v:visit12345");
ok(on.likes === 30, "switch on (x10): likes x10");
ok(on.views === 370, "switch on: views x10, as before");
ok(on.shares === 2, "shares unchanged");
ok(on.liked === true, "liked still per actor");
ok((await db.query(`select likes from ad_campaign_engagement where campaign_id = '00000000-0000-4000-8000-000000000002'`)).rows[0].likes === 3, "the stored count stays real (display only)");
for (const role of ["anon", "authenticated"]) ok(!(await db.query(`select has_function_privilege('${role}', 'public.ad_engagement(uuid, text)', 'execute') v`)).rows[0].v, `${role} cannot call it`);
console.log(failures ? `\n${failures} FAILED${MUTANT ? " (expected under --mutant)" : ""}` : "\nALL PASSED");
process.exit(failures ? 1 : 0);
